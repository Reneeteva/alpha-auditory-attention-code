%% ============================================================
% LINEAR MIXED-EFFECTS MODEL
%
% RESEARCH QUESTION:
%
% Does auditory condition predict reaction time
% AFTER controlling for presentation order?
%
% OUTCOME VARIABLE:
% Standardized Reaction Time (Z_RT)
%
% PREDICTORS:
% 1. Auditory Condition:
%       Silence
%       Slow
%       Fast
%
% 2. Presentation Round:
%       Round 1
%       Round 2
%       Round 3
%
% MODEL:
%
% Z_RT ~ Condition + Round + (1 | Subject)
%
% INTERPRETATION:
%
% The Condition effect tells us whether auditory condition
% is associated with reaction time when presentation order
% is statistically held constant.
%
% The Round effect tells us whether response time changes
% between the first, second, and third rounds,
% independently of auditory condition.
%
% STANDARDIZATION:
%
% For EACH participant separately:
%
% 1. Take all valid RT trials from all 3 conditions together
% 2. Convert the complete valid RT list to Z-scores
% 3. Keep each individual trial as one observation
%
% IMPORTANT:
%
% REMOVE_OUTLIERS = false;
%
% means:
% Subjects 6 and 8 are removed for consistency
% with the main inferential RT analyses.
%
% Change to false to keep all participants.
%% ============================================================

clear;
clc;
close all;


%% ============================================================
% SETTINGS
%% ============================================================

REMOVE_OUTLIERS = true;


%% ============================================================
% 1. CHOOSE PARTICIPANT FOLDER
%% ============================================================

path = uigetdir( ...
    pwd, ...
    'Choose the folder containing participant files');


if isequal(path, 0)

    error('No folder was selected.');

end


fprintf('\nSelected folder:\n%s\n', ...
    path);


%% ============================================================
% 2. FIND PARTICIPANT FILES
%% ============================================================

xlsx_files = ...
    dir(fullfile(path, '*exel sub*.xlsx'));

xls_files = ...
    dir(fullfile(path, '*exel sub*.xls'));

csv_files = ...
    dir(fullfile(path, '*exel sub*.csv'));


all_files = [ ...
    xlsx_files; ...
    xls_files; ...
    csv_files];


files = ...
    {all_files.name};


n_subjects_original = ...
    length(files);


fprintf('\nFound %d participant files:\n', ...
    n_subjects_original);


disp(files');


if n_subjects_original < 2

    error('MATLAB found fewer than 2 participant files.');

end


%% ============================================================
% 3. PREPARE ONE LARGE TRIAL-LEVEL DATASET
%% ============================================================

all_subjects = ...
    strings(0,1);


all_RT_new = ...
    zeros(0,1);


all_conditions = ...
    strings(0,1);


all_round_numbers = ...
    zeros(0,1);
%% Prepare subject-level outlier information

subject_names_for_outlier_check = ...
    strings(0,1);

subject_mean_logRT_for_outlier_check = ...
    zeros(0,1);

%% ============================================================
% 4. ANALYZE EACH PARTICIPANT
%% ============================================================

for s = 1:n_subjects_original


    filename = ...
        fullfile(path, files{s});


    %% Read file

    T = readtable( ...
        filename, ...
        'VariableNamingRule', ...
        'preserve');


    %% Participant name

    [~, name, ~] = ...
        fileparts(files{s});


    current_subject = ...
        string(name);


    %% --------------------------------------------------------
    % READ VARIABLES
    %% --------------------------------------------------------

    % Column B = auditory condition

    auditory_condition = ...
        lower(strtrim(string(T{:,2})));


    % Column F = action/status

    action_status = ...
        str2double(string(T{:,6}));


    % Column G = reaction time

    RT_ms = ...
        str2double(string(T{:,7}));


    % Column H = error

    errors = ...
        str2double(string(T{:,8}));


    %% ========================================================
    % 4A. DETERMINE PRESENTATION ORDER
    %
    % The code finds which condition appeared first,
    % second, and third in this participant's file.
    %% ========================================================

    condition_names = [ ...
        "silence"; ...
        "slow"; ...
        "fast"];


    first_occurrence = ...
        NaN(3,1);


    for c = 1:3


        first_row = ...
            find( ...
            auditory_condition == condition_names(c), ...
            1, ...
            'first');


        if ~isempty(first_row)

            first_occurrence(c) = ...
                first_row;

        end


    end


    %% Check that all 3 conditions exist

    if any(isnan(first_occurrence))

        warning( ...
            '%s does not contain all 3 conditions.', ...
            files{s});

        continue;

    end


    %% Sort conditions by their first appearance

    [~, presentation_order] = ...
        sort(first_occurrence);


    %% Create mapping:
    %
    % condition_round(c) tells us whether
    % condition c was presented in Round 1, 2, or 3.

    condition_round = ...
        NaN(3,1);


    for round_number = 1:3

        condition_index = ...
            presentation_order(round_number);


        condition_round(condition_index) = ...
            round_number;

    end


    %% Create round number for every row

    round_number_per_trial = ...
        NaN(height(T),1);


    for c = 1:3

        round_number_per_trial( ...
            auditory_condition == condition_names(c)) = ...
            condition_round(c);

    end


    %% Print participant order

    fprintf('\n%s\n', ...
        current_subject);


    fprintf( ...
        'Round 1 = %s\n', ...
        condition_names( ...
        presentation_order(1)));


    fprintf( ...
        'Round 2 = %s\n', ...
        condition_names( ...
        presentation_order(2)));


    fprintf( ...
        'Round 3 = %s\n', ...
        condition_names( ...
        presentation_order(3)));


    %% ========================================================
    % 4B. VALID RT TRIALS
    %% ========================================================

    valid_trials = ...
        action_status == 1 & ...
        errors == 0 & ...
        RT_ms < 4000 & ...
        ~isnan(RT_ms) & ...
        ~isnan(round_number_per_trial);


    %% All valid RTs for this participant

all_valid_RT = ...
    RT_ms(valid_trials);


%% Check that participant has enough valid trials

if numel(all_valid_RT) < 2 || ...
        std(all_valid_RT, 'omitnan') == 0

    warning( ...
        '%s does not have enough valid RT variability.', ...
        files{s});

    continue;

end


%% ========================================================
% 4C. LOG TRANSFORM RT AND REMOVE TRIAL-LEVEL OUTLIERS
%
% For the linear mixed-effects model, we do NOT use Z-scores.
% We use original RT values in milliseconds, apply log,
% and remove trial-level outliers within each participant.
%
% Outlier criterion:
% More than 2 standard deviations from the participant's
% mean log RT.
%% ========================================================

RT_new_all = ...
    log(all_valid_RT);

mean_log_RT = ...
    mean(RT_new_all, 'omitnan');

std_log_RT = ...
    std(RT_new_all, 'omitnan');

log_RT_outlier = ...
    abs(RT_new_all - mean_log_RT) > 2 * std_log_RT;

RT_new = ...
    RT_new_all(~log_RT_outlier);
%% Save participant mean log RT for subject-level outlier check

subject_names_for_outlier_check = [ ...
    subject_names_for_outlier_check; ...
    current_subject];

subject_mean_logRT_for_outlier_check = [ ...
    subject_mean_logRT_for_outlier_check; ...
    mean(RT_new, 'omitnan')];

%% Get condition and order for valid observations

valid_conditions_all = ...
    auditory_condition(valid_trials);

valid_rounds_all = ...
    round_number_per_trial(valid_trials);

valid_conditions = ...
    valid_conditions_all(~log_RT_outlier);

valid_rounds = ...
    valid_rounds_all(~log_RT_outlier);


%% Subject ID repeated for every valid trial

valid_subjects = ...
    repmat( ...
    current_subject, ...
    numel(RT_new), ...
    1);
    %% ========================================================

    all_subjects = [ ...
        all_subjects; ...
        valid_subjects];

    all_RT_new = [ ...
        all_RT_new; ...
        RT_new];

    all_conditions = [ ...
        all_conditions; ...
        valid_conditions];


    all_round_numbers = [ ...
        all_round_numbers; ...
        valid_rounds];


end


%% ============================================================
% 5. CREATE TRIAL-LEVEL TABLE
%% ============================================================

model_data = table( ...
    all_subjects, ...
    all_RT_new, ...
    all_conditions, ...
    all_round_numbers);

model_data.Properties.VariableNames = { ...
    'Subject', ...
    'RT_new', ...
    'Condition_String', ...
    'Round_Number'};


%% ============================================================
% 6. AUTOMATIC SUBJECT-LEVEL OUTLIER REMOVAL
%
% This checks whether a participant's mean log RT is more than
% 2 standard deviations from the group mean.
%
% If REMOVE_OUTLIERS = true:
% Participants identified as subject-level outliers are removed.
%
% If REMOVE_OUTLIERS = false:
% No participants are removed.
%% ============================================================

if REMOVE_OUTLIERS

    group_mean_logRT = ...
        mean(subject_mean_logRT_for_outlier_check, 'omitnan');

    group_std_logRT = ...
        std(subject_mean_logRT_for_outlier_check, 'omitnan');

    subject_level_outlier = ...
        abs(subject_mean_logRT_for_outlier_check - group_mean_logRT) > ...
        2 * group_std_logRT;

    subjects_to_remove = ...
        subject_names_for_outlier_check(subject_level_outlier);

    remove_trial = ...
        ismember( ...
        lower(strtrim(model_data.Subject)), ...
        lower(strtrim(subjects_to_remove)));

    fprintf('\n================================================\n');
    fprintf('AUTOMATIC SUBJECT-LEVEL OUTLIER CHECK\n');
    fprintf('================================================\n');

    fprintf('\nGroup mean log RT = %.4f\n', group_mean_logRT);
    fprintf('Group SD log RT = %.4f\n', group_std_logRT);

    fprintf('\nSubjects identified as outliers:\n');

    if isempty(subjects_to_remove)

        fprintf('None\n');

    else

        disp(subjects_to_remove);

    end

    model_data(remove_trial,:) = [];

else

    fprintf('\n================================================\n');
    fprintf('NO PARTICIPANTS REMOVED\n');
    fprintf('================================================\n');

end

%% ============================================================
% 7. CONVERT VARIABLES TO CATEGORICAL
%
% Reference categories:
%
% Condition:
% Silence = reference
%
% Round:
% Round 1 = reference
%% ============================================================

model_data.Subject = ...
    categorical( ...
        model_data.Subject);


model_data.Condition = ...
    categorical( ...
        model_data.Condition_String, ...
        ["silence", "slow", "fast"], ...
        ["Silence", "Slow", "Fast"]);


model_data.Round = ...
    categorical( ...
        model_data.Round_Number, ...
        [1, 2, 3], ...
        ["Round1", "Round2", "Round3"]);


%% Remove original helper columns

model_data.Condition_String = [];

model_data.Round_Number = [];


%% ============================================================
% 8. PRINT DATASET INFORMATION
%% ============================================================

n_trials = ...
    height(model_data);


n_subjects_final = ...
    numel( ...
        categories( ...
        removecats(model_data.Subject)));


fprintf('\n================================================\n');
fprintf('MODEL DATASET\n');
fprintf('================================================\n');


fprintf('\nParticipants = %d\n', ...
    n_subjects_final);


fprintf('Valid trial observations = %d\n', ...
    n_trials);


fprintf('\nObservations by condition:\n');

disp( ...
    groupcounts( ...
        model_data, ...
        'Condition'));


fprintf('\nObservations by round:\n');

disp( ...
    groupcounts( ...
        model_data, ...
        'Round'));


%% ============================================================
% 9. FIT LINEAR MIXED-EFFECTS MODEL
%
% Fixed effects:
%
% Condition
% Round
%
% Random effect:
%
% Participant-specific intercept
%
% This controls for repeated observations from the same person.
%% ============================================================

lme = fitlme( ...
    model_data, ...
    'RT_new ~ Condition + Round + (1|Subject)');


%% ============================================================
% 10. PRINT COMPLETE MODEL
%% ============================================================

fprintf('\n================================================\n');
fprintf('LINEAR MIXED-EFFECTS MODEL\n');
fprintf('================================================\n');


disp(lme);


%% ============================================================
% 11. COEFFICIENT TABLE
%% ============================================================

coefficient_table = ...
    lme.Coefficients;


fprintf('\n================================================\n');
fprintf('MODEL COEFFICIENTS\n');
fprintf('================================================\n');


disp(coefficient_table);


%% ============================================================
% 12. OVERALL TESTS FOR CONDITION AND ORDER
%
% THIS IS VERY IMPORTANT.
%
% The ANOVA table gives:
%
% 1. Overall p-value for Condition
%
%    Does auditory condition explain RT
%    after controlling for Round?
%
% 2. Overall p-value for Round
%
%    Does presentation order explain RT
%    after controlling for Condition?
%% ============================================================

model_effects = ...
    anova(lme);
%% Convert ANOVA output to table for Excel saving

%% ============================================================
% CREATE A REGULAR TABLE FOR EXCEL
%% ============================================================

% The model contains these fixed effects:
effect_names = [ ...
    "(Intercept)"; ...
    "Condition"; ...
    "Round"];

% Number of rows returned by ANOVA
n_effect_rows = size(model_effects, 1);

% Keep only the correct number of names
effect_names = effect_names(1:n_effect_rows);

%% Create regular MATLAB table

model_effects_table = table( ...
    effect_names, ...
    model_effects.FStat, ...
    model_effects.DF1, ...
    model_effects.DF2, ...
    model_effects.pValue);

model_effects_table.Properties.VariableNames = { ...
    'Effect', ...
    'F_Statistic', ...
    'DF1', ...
    'DF2', ...
    'p_Value'};

%% Add significance result

model_effects_table.Statistically_Significant = ...
    model_effects_table.p_Value < 0.05;

fprintf('\n================================================\n');
fprintf('OVERALL MODEL EFFECTS - EXCEL TABLE\n');
fprintf('================================================\n');

disp(model_effects_table);

%% ============================================================
% 13. PRINT SIMPLE INTERPRETATION
%% ============================================================

fprintf('\n================================================\n');
fprintf('HOW TO INTERPRET THE MODEL\n');
fprintf('================================================\n');


