%% ============================================================
% ADD SIMPLE DIRECTION INTERPRETATION
%% ============================================================

direction = ...
    strings(6,1);


for k = 1:6

    if estimate(k) < 0

        direction(k) = ...
            "First item is faster than second";

    elseif estimate(k) > 0

