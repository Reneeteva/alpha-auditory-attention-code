    ];


fprintf('\n================================================\n');
fprintf('CLEAR OVERALL EFFECTS TABLE\n');
fprintf('================================================\n');


disp(overall_effects_clear);


%% ============================================================
% 14C. PREPARE COEFFICIENT INFORMATION
%% ============================================================

coef_names = ...
    string(coefficient_table.Name);


beta = ...
    coefficient_table.Estimate;


coefficient_covariance = ...
    lme.CoefficientCovariance;


%% Find coefficient positions

idx_slow = ...
    find(coef_names == "Condition_Slow");


idx_fast = ...
    find(coef_names == "Condition_Fast");


idx_round2 = ...
    find(coef_names == "Round_Round2");


idx_round3 = ...
    find(coef_names == "Round_Round3");


%% Use model degrees of freedom

contrast_DF = ...
    coefficient_table.DF(1);


%% ============================================================
% 14D. NEW COMPARISON:
% FAST vs SLOW
%
% Estimate:
% Fast coefficient - Slow coefficient
%% ============================================================

contrast_fast_slow = ...
    zeros(length(beta),1);


contrast_fast_slow(idx_fast) = ...
    1;


contrast_fast_slow(idx_slow) = ...
    -1;


estimate_fast_slow = ...
    contrast_fast_slow' * beta;


SE_fast_slow = ...
    sqrt( ...
        contrast_fast_slow' * ...
        coefficient_covariance * ...
        contrast_fast_slow);


t_fast_slow = ...
    estimate_fast_slow / ...
    SE_fast_slow;


p_fast_slow = ...
    2 * tcdf( ...
        -abs(t_fast_slow), ...
        contrast_DF);


critical_t = ...
    tinv( ...
        0.975, ...
        contrast_DF);


CI_fast_slow_lower = ...
    estimate_fast_slow - ...
    critical_t * SE_fast_slow;


CI_fast_slow_upper = ...
    estimate_fast_slow + ...
    critical_t * SE_fast_slow;


%% ============================================================
% 14E. NEW COMPARISON:
% ROUND 3 vs ROUND 2
%
% Estimate:
% Round 3 coefficient - Round 2 coefficient
%% ============================================================

contrast_round3_round2 = ...
    zeros(length(beta),1);


contrast_round3_round2(idx_round3) = ...
    1;


contrast_round3_round2(idx_round2) = ...
    -1;


estimate_round3_round2 = ...
    contrast_round3_round2' * beta;


SE_round3_round2 = ...
    sqrt( ...
        contrast_round3_round2' * ...
        coefficient_covariance * ...
        contrast_round3_round2);


t_round3_round2 = ...
    estimate_round3_round2 / ...
    SE_round3_round2;


p_round3_round2 = ...
    2 * tcdf( ...
        -abs(t_round3_round2), ...
        contrast_DF);


CI_round3_round2_lower = ...
    estimate_round3_round2 - ...
    critical_t * SE_round3_round2;


CI_round3_round2_upper = ...
    estimate_round3_round2 + ...
    critical_t * SE_round3_round2;


%% ============================================================
% 14F. CREATE ALL CONDITION COMPARISONS
%% ============================================================

condition_comparisons = [ ...
    "Slow vs Silence"; ...
    "Fast vs Silence"; ...
    "Fast vs Slow"];


condition_estimates = [ ...
    coefficient_table.Estimate(idx_slow); ...
    coefficient_table.Estimate(idx_fast); ...
    estimate_fast_slow];


condition_SE = [ ...
    coefficient_table.SE(idx_slow); ...
    coefficient_table.SE(idx_fast); ...
    SE_fast_slow];


condition_t = [ ...
    coefficient_table.tStat(idx_slow); ...
    coefficient_table.tStat(idx_fast); ...
    t_fast_slow];


condition_DF = [ ...
    coefficient_table.DF(idx_slow); ...
    coefficient_table.DF(idx_fast); ...
    contrast_DF];


condition_p_raw = [ ...
    coefficient_table.pValue(idx_slow); ...
    coefficient_table.pValue(idx_fast); ...
    p_fast_slow];


condition_CI_lower = [ ...
    coefficient_table.Lower(idx_slow); ...
    coefficient_table.Lower(idx_fast); ...
    CI_fast_slow_lower];


condition_CI_upper = [ ...
    coefficient_table.Upper(idx_slow); ...
    coefficient_table.Upper(idx_fast); ...
    CI_fast_slow_upper];


%% Bonferroni correction:
% 3 Condition comparisons

condition_p_bonferroni = ...
    min( ...
        condition_p_raw * 3, ...
        1);


condition_significant_after_bonferroni = ...
    condition_p_bonferroni < 0.05;


%% ============================================================
% 14G. CREATE ALL ROUND COMPARISONS
%% ============================================================

round_comparisons = [ ...
    "Round 2 vs Round 1"; ...
    "Round 3 vs Round 1"; ...
    "Round 3 vs Round 2"];


round_estimates = [ ...
    coefficient_table.Estimate(idx_round2); ...
    coefficient_table.Estimate(idx_round3); ...
    estimate_round3_round2];


round_SE = [ ...
    coefficient_table.SE(idx_round2); ...
    coefficient_table.SE(idx_round3); ...
    SE_round3_round2];


round_t = [ ...
    coefficient_table.tStat(idx_round2); ...
    coefficient_table.tStat(idx_round3); ...
    t_round3_round2];


round_DF = [ ...
    coefficient_table.DF(idx_round2); ...
    coefficient_table.DF(idx_round3); ...
    contrast_DF];


round_p_raw = [ ...
    coefficient_table.pValue(idx_round2); ...
    coefficient_table.pValue(idx_round3); ...
    p_round3_round2];


round_CI_lower = [ ...
    coefficient_table.Lower(idx_round2); ...
    coefficient_table.Lower(idx_round3); ...
    CI_round3_round2_lower];


round_CI_upper = [ ...
    coefficient_table.Upper(idx_round2); ...
    coefficient_table.Upper(idx_round3); ...
    CI_round3_round2_upper];


%% Bonferroni correction:
% 3 Round comparisons

round_p_bonferroni = ...
    min( ...
        round_p_raw * 3, ...
        1);


round_significant_after_bonferroni = ...
    round_p_bonferroni < 0.05;


%% ============================================================
% 14H. COMBINE ALL PAIRWISE COMPARISONS
%% ============================================================

comparison_family = [ ...
